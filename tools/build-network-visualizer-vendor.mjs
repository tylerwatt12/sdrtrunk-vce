#!/usr/bin/env node

import { build } from 'esbuild';
import { promises as fs } from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const repository = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = path.join(repository, 'tools', 'network-visualizer-vendor-entry.js');
const destination = path.join(repository, 'stats-web', 'assets', 'vendor');
const bundleName = 'network-visualizer-vendor.js';
const licenseName = 'network-visualizer-vendor.LICENSES.txt';
const check = process.argv.includes('--check');

async function packageMetadata(input) {
  let candidate = path.dirname(path.resolve(repository, input));
  while (candidate.startsWith(repository + path.sep)) {
    const manifest = path.join(candidate, 'package.json');
    try {
      const document = JSON.parse(await fs.readFile(manifest, 'utf8'));
      if (document.name && document.version) return { root: candidate, document };
    } catch (error) {
      if (error?.code !== 'ENOENT') throw error;
    }
    const parent = path.dirname(candidate);
    if (parent === candidate) break;
    candidate = parent;
  }
  return null;
}

async function licenseText(root) {
  const names = (await fs.readdir(root)).filter((name) => /^(licen[cs]e|copying)(?:\.|$)/i.test(name)).sort();
  if (!names.length) return 'No package license file was present in the installed package.';
  const parts = [];
  for (const name of names) parts.push((await fs.readFile(path.join(root, name), 'utf8')).trim());
  return [...new Set(parts)].join('\n\n');
}

async function licenses(metafile) {
  const packages = new Map();
  for (const input of Object.keys(metafile.inputs).sort()) {
    if (!input.replaceAll('\\', '/').split('/').includes('node_modules')) continue;
    const metadata = await packageMetadata(input);
    if (metadata) packages.set(`${metadata.document.name}@${metadata.document.version}`, metadata);
  }

  const sections = [
    'Network Visualizer browser bundle third-party licenses',
    '',
    'This file is generated by tools/build-network-visualizer-vendor.mjs from the exact packages in package-lock.json.',
    'The bundled libraries remain copyright their respective authors and are distributed under the terms below.'
  ];
  const orderedPackages = [...packages.entries()].sort(([left], [right]) => left < right ? -1 : left > right ? 1 : 0);
  for (const [identity, metadata] of orderedPackages) {
    const source = typeof metadata.document.repository === 'string' ? metadata.document.repository :
      metadata.document.repository?.url || metadata.document.homepage || '';
    sections.push('', '='.repeat(80), identity, `Declared license: ${metadata.document.license || 'unspecified'}`);
    if (source) sections.push(`Source: ${String(source).replace(/^git\+/, '')}`);
    sections.push('', await licenseText(metadata.root));
  }
  return `${sections.join('\n').trimEnd()}\n`;
}

async function generate(outputDirectory) {
  await fs.mkdir(outputDirectory, { recursive: true });
  const bundle = path.join(outputDirectory, bundleName);
  const result = await build({
    absWorkingDir: repository,
    banner: { js: `/*! Network Visualizer vendor bundle; see ${licenseName}. */` },
    bundle: true,
    entryPoints: [entry],
    format: 'esm',
    legalComments: 'none',
    metafile: true,
    minify: true,
    outfile: bundle,
    platform: 'browser',
    sourcemap: false,
    target: ['es2022']
  });
  const bundleText = await fs.readFile(bundle, 'utf8');
  await fs.writeFile(bundle, bundleText.replace(/[ \t]+$/gm, '').replace(/^ +(?=\t)/gm, ''));
  await fs.writeFile(path.join(outputDirectory, licenseName), await licenses(result.metafile));
}

async function equal(left, right) {
  try {
    const [leftBytes, rightBytes] = await Promise.all([fs.readFile(left), fs.readFile(right)]);
    return leftBytes.equals(rightBytes);
  } catch (error) {
    if (error?.code === 'ENOENT') return false;
    throw error;
  }
}

if (check) {
  const temporary = await fs.mkdtemp(path.join(os.tmpdir(), 'sdrtrunk-network-visualizer-vendor-'));
  try {
    await generate(temporary);
    const artifacts = [bundleName, licenseName];
    const stale = [];
    for (const artifact of artifacts) {
      if (!await equal(path.join(temporary, artifact), path.join(destination, artifact))) stale.push(artifact);
    }
    if (stale.length) {
      throw new Error(`Generated Network Visualizer vendor artifacts are stale: ${stale.join(', ')}`);
    }
    process.stdout.write('Network Visualizer vendor artifacts are current.\n');
  } finally {
    await fs.rm(temporary, { recursive: true, force: true });
  }
} else {
  await generate(destination);
  process.stdout.write(`Generated ${path.relative(repository, path.join(destination, bundleName))}.\n`);
  process.stdout.write(`Generated ${path.relative(repository, path.join(destination, licenseName))}.\n`);
}
