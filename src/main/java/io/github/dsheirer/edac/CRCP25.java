    /**
     * Creates the single-bit syndromes for the 80 data bits followed by the 16 CRC bits in a P25 header or TSBK.
     * The CRC bits are transmitted most-significant bit first.
     */
    private static int[] createCCITT80Syndromes()
    {
        int[] syndromes = new int[CCITT_MESSAGE_LENGTH + CCITT_CRC_LENGTH];

        for(int bit = 0; bit < CCITT_MESSAGE_LENGTH; bit++)
        {
            int remainder = 1;

            for(int shift = 0; shift < CCITT_CRC_LENGTH + CCITT_MESSAGE_LENGTH - bit - 1; shift++)
            {
                boolean highBit = (remainder & 0x8000) != 0;
                remainder = (remainder << 1) & 0xFFFF;

                if(highBit)
                {
                    remainder ^= (int)CRC_16_POLYNOMIAL;
                }
            }

            syndromes[bit] = remainder;
        }

        for(int bit = 0; bit < CCITT_CRC_LENGTH; bit++)
        {
            syndromes[CCITT_MESSAGE_LENGTH + bit] = 1 << (CCITT_CRC_LENGTH - bit - 1);
        }

        return syndromes;
    }

