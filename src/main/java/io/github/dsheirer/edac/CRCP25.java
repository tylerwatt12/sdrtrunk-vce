    /**
     * Error detection and correction of single-bit errors for CCITT 16-bit
     * CRC protected 80-bit messages.
     */
    public static int correctCCITT80(CorrectedBinaryMessage message, int messageStart, int crcStart)
    {
        if(crcStart - messageStart != CCITT_MESSAGE_LENGTH || message.size() < crcStart + CCITT_CRC_LENGTH)
        {
            throw new IllegalArgumentException("P25 CRC-CCITT requires 80 data bits followed by 16 CRC bits");
        }

        int calculated = (int)calculateCRC(message, messageStart, crcStart, CCITT_CRC_LENGTH,
            CRC_16_POLYNOMIAL, CRC_16_INVERSION);
        int checksum = getIntChecksum(message, crcStart, CCITT_CRC_LENGTH);
        int residual = calculated ^ checksum;

        if(residual == 0)
        {
            return 0;
        }

        int errorLocation = getBitError(residual, CCITT_80_SYNDROMES);

        if(errorLocation >= 0)
        {
            message.flip(errorLocation + messageStart);
            message.incrementCorrectedBitCount(1);
            return 1;
        }

        //The residual isn't a correctable single-bit error.
        message.incrementCorrectedBitCount(2);

        return 2;
    }

    /**
     * Error detection for CRC-9 protected Confirmed Packet Data blocks.  The seven-bit block serial number and
     * 128 data bits are protected as one 135-bit value, while the transmitted CRC occupies bits 7-15 of the decoded
     * 144-bit block.  No data correction is performed.
     */
    public static CRC checkCRC9(BinaryMessage message, int messageStart)
    {
        if(message.size() < messageStart + 144)
        {
            return CRC.FAILED_CRC;
        }

        long remainder = calculateCRC(message, messageStart, messageStart + 7, CRC_9_LENGTH,
            CRC_9_POLYNOMIAL, 0);
        remainder = updateCRC(remainder, message, messageStart + 16, messageStart + 144, CRC_9_LENGTH,
            CRC_9_POLYNOMIAL);
        int calculated = (int)(remainder ^ CRC_9_INVERSION);
        int checksum = message.getInt(messageStart + 7, messageStart + 15);
        return calculated == checksum ? CRC.PASSED : CRC.FAILED_CRC;
    }

    /**
     * Checks the four-octet packet CRC defined by TIA-102.BAAA-A section 6.3.3.  The CRC covers all data and pad bits
     * before the CRC field and does not include the PDU header or confirmed-block sequence/CRC-9 fields.
     *
     * @param message containing the contiguous packet payload and CRC
     * @param messageStart first packet data bit
     * @param crcStart first bit of the transmitted 32-bit CRC
     * @return pass when the transmitted CRC exactly matches the specified inverted CRC
     */
    public static CRC checkCRC32(BinaryMessage message, int messageStart, int crcStart)
    {
        if(messageStart < 0 || crcStart <= messageStart || message.size() < crcStart + CRC_32_LENGTH)
        {
            return CRC.FAILED_CRC;
        }

        long calculated = calculateCRC(message, messageStart, crcStart, CRC_32_LENGTH, CRC_32_POLYNOMIAL,
            CRC_32_INVERSION);
        long checksum = getLongChecksum(message, crcStart, CRC_32_LENGTH);
        return calculated == checksum ? CRC.PASSED : CRC.FAILED_CRC;
    }

    /**
     * Calculates a direct, non-reflected CRC over the specified bit range.  Data is processed most-significant bit
     * first, matching the polynomial definitions in TIA-102.BAAA-A sections 6.2, 6.3.3, and 6.4.2.
     */
    private static long calculateCRC(BinaryMessage message, int messageStart, int messageEnd, int crcLength,
                                     long polynomial, long inversion)
    {
        return updateCRC(0, message, messageStart, messageEnd, crcLength, polynomial) ^ inversion;
    }

    private static long updateCRC(long remainder, BinaryMessage message, int messageStart, int messageEnd,
                                  int crcLength, long polynomial)
    {
        long highBit = 1L << (crcLength - 1);
        long mask = (1L << crcLength) - 1;

        for(int bit = messageStart; bit < messageEnd; bit++)
        {
            boolean feedback = ((remainder & highBit) != 0) ^ message.get(bit);
            remainder = (remainder << 1) & mask;

            if(feedback)
            {
                remainder ^= polynomial;
            }
        }

        return remainder;
    }


    /**
     * Performs extended Golay (24,12,8) error detection and correction against the 12
     * encoded 24-bit message segments following the 64-bit NID in the message
     *
     * @return - true if all 12 segments of the message can be checked/corrected
     */
    public static boolean correctGalois24(CorrectedBinaryMessage tdulc)
    {
        boolean passes = true;

        int x = 64;

        while(x < tdulc.size() && passes)
        {

            int errors = Golay24.checkAndCorrect(tdulc, x);

            passes = errors < 2;

            x += 24;
        }

        return passes;
    }

    /**
     * Calculates the CRC-12 checksum for the P25 Phase 2 MAC PDU Contents for S-OEMI/FACCH and compares it to the
     * transmitted checksum to verify that the message is correct.
     * Note: this uses the pre-calculated checksums in the CRC_12_FACCH array.
     *
     * @param message to verify
     * @return true if the message passes the CRC-12 check.
     */
    public static boolean crc12Facch(CorrectedBinaryMessage message)
    {
        int calculated = 0xFFF; //Initial fill of all ones.

        //Iterate the set bits and XOR the running checksum with pre-calculated lookup value
        for(int i = message.nextSetBit(0); i >= 0 && i < 144; i = message.nextSetBit(i + 1))
        {
            calculated ^= CRC_12_FACCH[i];
        }

        int checksum = message.getInt(144, 155); //12-bit transmitted checksum
        int residual = calculated ^ checksum;
        return residual == 0;
    }

